import crypto from "crypto";

/**
 * Personal data export (GDPR/Kenya DPA style subject access export).
 * Requires recent reauthentication because the file contains decrypted
 * vault content. Generated synchronously with a size guard.
 */

const MAX_EXPORT_BYTES = 5 * 1024 * 1024;

export const GET = handleRoute(async () => {
  const ctx = await requireUser();
  const requests = await db.q(
    `SELECT id, status, error, requested_at, completed_at, document_id
       FROM data_export_requests WHERE user_id = $1 ORDER BY requested_at DESC LIMIT 10`,
    [ctx.user.id],
  );
  return ok({ requests });
});

export const POST = handleRoute(async (req) => {
  assertSameOrigin(req);
  const ctx = await requireUser();
  requireRecentReauth(ctx, 30);
  const { ip, userAgent } = await currentIpAndAgent();

  const request = await db.q1<{ id: string }>(
    `INSERT INTO data_export_requests (user_id, status) VALUES ($1, 'pending') RETURNING id`,
    [ctx.user.id],
  );
  if (!request) throw new Error("Could not create export request");

  try {
    const payload = await buildExport(ctx.user.id);
    const json = JSON.stringify(payload, null, 2);
    const buf = Buffer.from(json, "utf8");
    if (buf.length > MAX_EXPORT_BYTES) {
      throw new Error(`Export exceeds ${MAX_EXPORT_BYTES} bytes`);
    }

    const vault = await db.q1<{ id: string }>(`SELECT id FROM vaults WHERE user_id = $1`, [ctx.user.id]);
    if (!vault) throw new Error("Vault missing");

    const documentId = crypto.randomUUID();
    const storageKey = newDocumentKey(vault.id, documentId);
    const dek = await getVaultDek(vault.id);
    // Exports are stored as ordinary vault documents, so they must use the
    // same AAD as uploads or the download endpoint cannot decrypt them.
    const sealed = encryptBuffer(buf, dek, "documents:content");
    dek.fill(0);
    await getStorage().put(storageKey, sealed.ciphertext);

    const checksum = crypto.createHash("sha256").update(buf).digest("hex");
    const doc = await db.q1<{ id: string; title: string }>(      `INSERT INTO documents
         (id, vault_id, title, category, notes, filename, mime_type, size_bytes, checksum_sha256, storage_key, enc_iv, enc_tag, scan_status, scan_detail, uploaded_by, tags)
       VALUES ($1, $2, $3, 'export', 'Personal data export generated by AfterKey', $4, 'application/json', $5, $6, $7, $8, $9, 'skipped', 'server-generated export', $10, '{export}')
       RETURNING id, title`,
      [
        documentId,
        vault.id,
        `Data export ${new Date().toISOString().slice(0, 10)}`,
        `afterkey-export-${new Date().toISOString().slice(0, 10)}.json`,
        buf.length,
        checksum,
        storageKey,
        sealed.iv,
        sealed.tag,
        ctx.user.id,
      ],
    );
    if (!doc) throw new Error("Could not store the export document");

    await db.raw(
      `UPDATE data_export_requests SET status = 'ready', document_id = $2, completed_at = now() WHERE id = $1`,
      [request.id, doc.id],
    );

    await queueEmail({
      to: ctx.user.email,
      template: "data_export_ready",
      rendered: renderEmail("data_export_ready", { url: appUrl("/settings/privacy") }),
      userId: ctx.user.id,
      relatedType: "export",
      relatedId: request.id,
      dedupeKey: `export:${request.id}`,
    });
    await recordAudit({
      action: "account.data_exported",
      actorType: "user",
      actorId: ctx.user.id,
      actorLabel: ctx.user.email,
      ip,
      userAgent,
      metadata: { requestId: request.id, bytes: buf.length },
    });

    return ok({ ok: true, documentId: doc.id, bytes: buf.length, requestId: request.id });
  } catch (err) {
    await db.raw(`UPDATE data_export_requests SET status = 'failed', error = $2 WHERE id = $1`, [
      request.id,
      (err instanceof Error ? err.message : "export failed").slice(0, 300),
    ]);
    return fail(500, "export_failed", "We could not generate your export. Please try again.");
  }
});

interface ExportBundle {
  generatedAt: string;
  account: Record<string, unknown>;
  vault: Record<string, unknown>;
}

async function buildExport(userId: string): Promise<ExportBundle> {
  const user = await db.q1<Record<string, unknown>>(
    `SELECT email, full_name, role, status, timezone, locale, notification_prefs, email_verified_at, created_at, mfa_enabled
       FROM users WHERE id = $1`,
    [userId],
  );
  const vault = await db.q1<{ id: string; name: string }>(`SELECT id, name FROM vaults WHERE user_id = $1`, [userId]);
  if (!user || !vault) throw new Error("Account data missing");

  const dek = await getVaultDek(vault.id);
  try {
    const [financial, digital, documents, properties, memories, recipients, permissions, schedule, policy, exports_, deletions, auditEvents] =
      await Promise.all([
        db.q(`SELECT * FROM financial_records WHERE vault_id = $1 ORDER BY created_at`, [vault.id]),
        db.q(`SELECT * FROM digital_accounts WHERE vault_id = $1 ORDER BY created_at`, [vault.id]),
        db.q(
          `SELECT id, title, category, notes, tags, filename, mime_type, size_bytes, uploaded_at, archived_at
             FROM documents WHERE vault_id = $1 AND deleted_at IS NULL ORDER BY uploaded_at`,
          [vault.id],
        ),
        db.q(`SELECT * FROM properties WHERE vault_id = $1 ORDER BY created_at`, [vault.id]),
        db.q(`SELECT * FROM memories WHERE vault_id = $1 ORDER BY created_at`, [vault.id]),
        db.q(`SELECT id, display_name, email, relationship, status, created_at FROM recipients WHERE vault_id = $1`, [vault.id]),
        db.q(
          `SELECT rp.* FROM recipient_permissions rp JOIN recipients r ON r.id = rp.recipient_id WHERE r.vault_id = $1`,
          [vault.id],
        ),
        db.q(`SELECT * FROM checkin_schedules WHERE user_id = $1`, [userId]),
        db.q(`SELECT p.* FROM release_policies p JOIN vaults v ON v.id = p.vault_id WHERE v.user_id = $1`, [userId]),
        db.q(`SELECT id, status, requested_at, completed_at FROM data_export_requests WHERE user_id = $1 ORDER BY requested_at`, [userId]),
        db.q(`SELECT id, status, reason, requested_at, completed_at FROM data_deletion_requests WHERE user_id = $1 ORDER BY requested_at`, [userId]),
        db.q(
          `SELECT action, target_type, target_id, metadata, occurred_at FROM audit_events
            WHERE actor_id = $1 ORDER BY occurred_at DESC LIMIT 500`,
          [userId],
        ),
      ]);

    // Rows arrive camelized; AADs must match encryption time exactly:
    //   financial/digital/properties -> `${table}:${camelField}`
    //   memories body                -> `memories:body`
    const decryptAll = <T extends Record<string, unknown>>(
      rows: T[],
      fields: Array<[field: string, aad: string]>,
    ): Array<Record<string, unknown>> =>
      rows.map((row) => {
        const out: Record<string, unknown> = { ...row };
        for (const [f, aad] of fields) {
          const value = out[f];
          if (typeof value === "string" && value.startsWith("enc:v1:")) {
            out[f] = decryptMaybe(value, dek, aad);
          }
        }
        return out;
      });

    return {
      generatedAt: new Date().toISOString(),
      account: { ...user, password_hash: undefined },
      vault: {
        name: vault.name,
        financialRecords: decryptAll(financial as Array<Record<string, unknown>>, [
          ["claimInstructions", "financial_records:claimInstructions"],
          ["notes", "financial_records:notes"],
        ]),
        digitalAccounts: decryptAll(digital as Array<Record<string, unknown>>, [
          ["recoveryInstructions", "digital_accounts:recoveryInstructions"],
          ["notes", "digital_accounts:notes"],
        ]),
        documents: documents as unknown[],
        properties: decryptAll(properties as Array<Record<string, unknown>>, [
          ["emergencyInstructions", "properties:emergencyInstructions"],
        ]),
        messages: decryptAll(memories as Array<Record<string, unknown>>, [
          ["body", "memories:body"],
        ]),
        recipients: recipients as unknown[],
        recipientPermissions: permissions as unknown[],
        checkinSchedules: schedule as unknown[],
        releasePolicies: policy as unknown[],
        dataExports: exports_ as unknown[],
        dataDeletions: deletions as unknown[],
        recentSecurityEvents: auditEvents as unknown[],
      },
    };
  } finally {
    dek.fill(0);
  }
}

